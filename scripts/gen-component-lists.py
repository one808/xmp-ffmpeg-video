#!/usr/bin/env python3
"""Generate --enable-decoder=... (audio only), --enable-demuxer=...,
--enable-parser=... and --enable-bsf=... argument lists from an FFmpeg source
tree. Used by build-ffmpeg.sh so the plugin's "play any audio, incl. the audio
track of video files" coverage follows the FFmpeg version automatically.

Decoder classification: libavcodec declares every decoder in allcodecs.c, but
many are generated by macros (pcm_*, adpcm_*) and thus carry no .p.type in the
source. Strategy: trust FFCodec blocks where present; for the rest, treat
PCM/ADPCM/DPCM/DSD families as audio and drop hardware-accel wrappers
(*_cuvid, *_qsv, ...) and known video leftovers.

usage: gen-component-lists.py <ffmpeg-src-dir>
prints: DECODERS=... DEMUXERS=... PARSERS=... BSFS=... (one per line)
"""
import re
import glob
import sys

src_dir = sys.argv[1]
avc = src_dir + "/libavcodec"

# name -> AVMEDIA_TYPE_x from explicit FFCodec definitions
cls = {}
for f in glob.glob(avc + "/*.c"):
    txt = open(f, encoding="utf-8", errors="replace").read()
    for m in re.finditer(r"FFCodec\s+ff_(\w+)_decoder\s*=\s*\{(.*?)\n\};", txt, re.S):
        t = re.search(r"\.p\.type\s*=\s*(AVMEDIA_TYPE_\w+)", m.group(2))
        cls[m.group(1)] = t.group(1) if t else "UNKNOWN"

allsrc = open(avc + "/allcodecs.c", encoding="utf-8", errors="replace").read()
all_decs = re.findall(r"extern const FFCodec ff_(\w+)_decoder;", allsrc)
fmtsrc = open(src_dir + "/libavformat/allformats.c", encoding="utf-8", errors="replace").read()
psrsrc = open(avc + "/parsers.c", encoding="utf-8", errors="replace").read()
bsfsrc = open(avc + "/bitstream_filters.c", encoding="utf-8", errors="replace").read()

HW_SUFFIX = ("_at", "_mediacodec", "_cuvid", "_qsv", "_amf", "_v4l2m2m",
             "_mmal", "_rkmpp", "_oh", "_vulkan")
VIDEO_LEFTOVER = {"hevc", "vvc"}  # macro-generated video decoders


def is_audio(name):
    t = cls.get(name)
    if t == "AVMEDIA_TYPE_AUDIO":
        return True
    if t in ("AVMEDIA_TYPE_VIDEO", "AVMEDIA_TYPE_SUBTITLE", "AVMEDIA_TYPE_DATA"):
        return False
    # unclassified (macro-generated)
    if name.endswith(HW_SUFFIX) or name in VIDEO_LEFTOVER:
        return False
    return (name.startswith(("pcm_", "adpcm_")) or name.endswith("_dpcm")
            or name.startswith(("dsd_", "aac", "ac3", "eac3", "mp1", "mp2", "mp3"))
            or name in {"opus", "speex", "vorbis", "libcodec2"})


decoders = sorted(n for n in all_decs if is_audio(n))
# all software decoders (audio + video + subtitle) for the video-window variant
alldec = sorted(n for n in all_decs if not n.endswith(HW_SUFFIX))

demuxers = sorted(set(re.findall(r"extern const FFInputFormat\s+ff_(\w+)_demuxer;", fmtsrc)))
parsers = sorted(set(re.findall(r"extern const FFCodecParser\s+ff_(\w+)_parser;", psrsrc)))
bsfs = sorted(set(re.findall(r"extern const FFBitStreamFilter\s+ff_(\w+)_bsf;", bsfsrc)))

sanity = {"aac", "flac", "mp3", "opus", "vorbis", "pcm_s16le", "alac", "ape",
          "wmav2", "dca", "truehd", "ac3", "amrnb", "wavpack"}
missing = sanity - set(decoders)
if missing:
    print("WARNING: sanity decoders missing:", ",".join(sorted(missing)), file=sys.stderr)

print("DECODERS=" + ",".join(decoders))
print("ALLDECODERS=" + ",".join(alldec))
print("DEMUXERS=" + ",".join(demuxers))
print("PARSERS=" + ",".join(parsers))
print("BSFS=" + ",".join(bsfs))
print("# decoders=%d demuxers=%d parsers=%d bsfs=%d" %
      (len(decoders), len(demuxers), len(parsers), len(bsfs)), file=sys.stderr)
